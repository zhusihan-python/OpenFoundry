// Command sqlc-policy enforces the honest status of SQLC integration.
//
// Default mode validates the repo's declaration (sqlc-policy.yaml) against
// the real sqlc.yaml shape and the tracked file inventory. --generate is the
// single generation entry shared by `make gen-sqlc` and CI: it runs the same
// policy gate first (so generation can never bypass it), then either runs a
// real `sqlc generate` or reports an explicit not-applicable status — it
// never fakes a successful generation, and it never fails merely because the
// caller's worktree is dirty (updating generated code is its job).
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	statusNotIntegrated = "not-integrated"
	statusIntegrated    = "integrated"
)

// Assembled in two pieces so this file never carries the literal generated
// header and can never flag itself in the inventory scan.
var generatedHeader = "// Code generated by sql" + "c. DO NOT EDIT."

// parseSingleDoc decodes exactly one YAML document. A second document or any
// trailing document is rejected: yaml.Unmarshal would silently keep only the
// first and mask whatever follows the separator.
func parseSingleDoc(b []byte, name string) (*yaml.Node, error) {
	dec := yaml.NewDecoder(bytes.NewReader(b))
	var doc yaml.Node
	if err := dec.Decode(&doc); err != nil {
		if errors.Is(err, io.EOF) {
			return nil, fmt.Errorf("%s: empty document", name)
		}
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	var extra yaml.Node
	if err := dec.Decode(&extra); errors.Is(err, io.EOF) {
		return &doc, nil
	} else if err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	return nil, fmt.Errorf("%s: multiple YAML documents are not allowed", name)
}

// topMapping returns the mapping node of a single-document YAML file.
func topMapping(b []byte, name string) (*yaml.Node, error) {
	doc, err := parseSingleDoc(b, name)
	if err != nil {
		return nil, err
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) == 0 {
		return nil, fmt.Errorf("%s: empty document", name)
	}
	top := doc.Content[0]
	if top.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("%s: top level must be a mapping", name)
	}
	return top, nil
}

// mapKeys collects a mapping's key/value pairs, reporting duplicates so a
// later `sql: []` can never mask an earlier real block.
func mapKeys(m *yaml.Node) (map[string]*yaml.Node, []string) {
	vals := map[string]*yaml.Node{}
	var dups []string
	for i := 0; i+1 < len(m.Content); i += 2 {
		k, v := m.Content[i], m.Content[i+1]
		if _, exists := vals[k.Value]; exists {
			dups = append(dups, k.Value)
			continue
		}
		vals[k.Value] = v
	}
	return vals, dups
}

type policyFile struct {
	Status     string
	Reason     string
	EnableWhen string
}

func loadPolicy(root string) (policyFile, []string, error) {
	b, err := os.ReadFile(filepath.Join(root, "sqlc-policy.yaml"))
	if err != nil {
		return policyFile{}, nil, err
	}
	top, err := topMapping(b, "sqlc-policy.yaml")
	if err != nil {
		return policyFile{}, nil, err
	}
	vals, dups := mapKeys(top)
	var viol []string
	for _, d := range dups {
		viol = append(viol, fmt.Sprintf("sqlc-policy.yaml: duplicate key %q", d))
	}
	for k := range vals {
		switch k {
		case "status", "reason", "enable_when":
		default:
			viol = append(viol, fmt.Sprintf("sqlc-policy.yaml: unknown key %q", k))
		}
	}
	var p policyFile
	for _, k := range []struct {
		name string
		dst  *string
	}{
		{"status", &p.Status},
		{"reason", &p.Reason},
		{"enable_when", &p.EnableWhen},
	} {
		v, ok := vals[k.name]
		if !ok {
			viol = append(viol, fmt.Sprintf("sqlc-policy.yaml: key %q is required", k.name))
			continue
		}
		if v.Kind != yaml.ScalarNode || v.Tag != "!!str" {
			viol = append(viol, fmt.Sprintf("sqlc-policy.yaml: %s must be a string (tag %s)", k.name, v.Tag))
			continue
		}
		*k.dst = v.Value
	}
	if p.Status != statusNotIntegrated && p.Status != statusIntegrated {
		viol = append(viol, "sqlc-policy.yaml: status must be not-integrated or integrated, got "+fmt.Sprintf("%q", p.Status))
	}
	if strings.TrimSpace(p.Reason) == "" || strings.TrimSpace(p.EnableWhen) == "" {
		viol = append(viol, "sqlc-policy.yaml: reason and enable_when must be non-empty")
	}
	return p, viol, nil
}

// sqlcSupported lists the top-level keys this pilot validates. sqlc 1.27's
// v2 config (internal/config/config.go) also accepts cloud, servers,
// overrides, plugins, rules and options — those are rejected as unsupported
// here instead of being silently accepted without validation.
var sqlcSupported = map[string]bool{"version": true, "sql": true}

// sqlEntries strictly parses sqlc.yaml and returns the sql sequence entries.
// A missing sql key, a non-list sql value, a wrong version, a duplicate key,
// or any key outside the supported set is reported as a violation — never
// silently treated as zero entries.
func sqlEntries(root string) ([]*yaml.Node, []string, error) {
	b, err := os.ReadFile(filepath.Join(root, "sqlc.yaml"))
	if err != nil {
		return nil, nil, err
	}
	top, err := topMapping(b, "sqlc.yaml")
	if err != nil {
		return nil, nil, err
	}
	vals, dups := mapKeys(top)
	var viol []string
	for _, d := range dups {
		viol = append(viol, fmt.Sprintf("sqlc.yaml: duplicate key %q — a later empty sql: [] cannot mask an earlier block", d))
	}
	for k := range vals {
		if !sqlcSupported[k] {
			viol = append(viol, fmt.Sprintf("sqlc.yaml: top-level key %q is not supported by this policy gate (only version and sql)", k))
		}
	}
	if v, ok := vals["version"]; !ok || v.Kind != yaml.ScalarNode || v.Tag != "!!str" || v.Value != "2" {
		viol = append(viol, `sqlc.yaml: version must be the string "2"`)
	}
	sqlNode, ok := vals["sql"]
	if !ok {
		return nil, append(viol, "sqlc.yaml: sql key is required — declare an empty list (sql: []) while not integrated"), nil
	}
	if sqlNode.Kind != yaml.SequenceNode {
		return nil, append(viol, "sqlc.yaml: sql must be a list (null, a mapping, or a scalar is not a zero-entry list)"), nil
	}
	return sqlNode.Content, viol, nil
}

// emptyPaths reports whether a schema/queries value carries no usable path.
func emptyPaths(n *yaml.Node) bool {
	switch n.Kind {
	case yaml.ScalarNode:
		return strings.TrimSpace(n.Value) == ""
	case yaml.SequenceNode:
		return len(n.Content) == 0
	default:
		return true
	}
}

// validateEntry checks one sql entry carries the keys sqlc needs to generate.
func validateEntry(i int, n *yaml.Node) []string {
	name := fmt.Sprintf("sqlc.yaml: sql[%d]", i)
	if n.Kind != yaml.MappingNode {
		return []string{name + " must be a mapping"}
	}
	keys, dups := mapKeys(n)
	var viol []string
	for _, d := range dups {
		viol = append(viol, fmt.Sprintf("%s: duplicate key %q", name, d))
	}
	for _, k := range []string{"engine", "schema", "queries"} {
		if v, ok := keys[k]; !ok || emptyPaths(v) {
			viol = append(viol, name+": "+k+" is required and must be non-empty")
		}
	}
	gen, ok := keys["gen"]
	if !ok || gen.Kind != yaml.MappingNode || len(gen.Content) == 0 {
		return append(viol, name+": gen with at least one generator (e.g. gen.go.out) is required when integrated")
	}
	for j := 0; j+1 < len(gen.Content); j += 2 {
		lang := gen.Content[j+1]
		if lang.Kind != yaml.MappingNode {
			viol = append(viol, fmt.Sprintf("%s: gen.%s must be a mapping", name, gen.Content[j].Value))
			continue
		}
		out, ok := langToKey(lang, "out")
		if !ok || strings.TrimSpace(out) == "" {
			viol = append(viol, fmt.Sprintf("%s: gen.%s.out is required and must be non-empty", name, gen.Content[j].Value))
		}
	}
	return viol
}

func langToKey(n *yaml.Node, key string) (string, bool) {
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1].Value, true
		}
	}
	return "", false
}

// gitFiles lists tracked plus untracked-not-ignored files, honoring
// .gitignore so node_modules, results and .git are never walked. -z keeps
// paths NUL-separated so names with spaces or non-ASCII survive intact.
func gitFiles(root string) ([]string, error) {
	out, err := exec.Command("git", "-C", root, "ls-files", "-z", "--cached", "--others", "--exclude-standard").Output()
	if err != nil {
		return nil, fmt.Errorf("git ls-files in %s: %w", root, err)
	}
	var files []string
	for _, p := range bytes.Split(out, []byte{0}) {
		if len(p) > 0 {
			files = append(files, string(p))
		}
	}
	return files, nil
}

// hasGeneratedHeader reports whether a .go file starts with a real sqlc
// generated header (within the first lines, alongside any build tags).
// This is a constraint on the claimed status, not a complete proof of
// generation provenance: hand-written files could omit the header, so the
// scan bounds what "not-integrated" asserts — it does not certify that every
// future generated file will carry it.
func hasGeneratedHeader(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer func() { _ = f.Close() }()
	sc := bufio.NewScanner(f)
	for i := 0; i < 8 && sc.Scan(); i++ {
		if strings.TrimSpace(sc.Text()) == generatedHeader {
			return true, nil
		}
	}
	return false, sc.Err()
}

// verify is the policy gate every mode funnels through: the repo may only
// claim what is true.
func verify(root string) ([]string, string, error) {
	p, viol, err := loadPolicy(root)
	if err != nil {
		return nil, "", err
	}
	entries, sqlcViol, err := sqlEntries(root)
	if err != nil {
		return nil, "", err
	}
	viol = append(viol, sqlcViol...)
	files, err := gitFiles(root)
	if err != nil {
		return nil, "", err
	}
	for _, f := range files {
		if base := filepath.Base(f); base == "sqlc.yaml" || base == "sqlc.yml" || base == "sqlc.json" {
			if f != "sqlc.yaml" {
				viol = append(viol, fmt.Sprintf("unexpected sqlc config %s — only the root sqlc.yaml is part of the declaration", f))
			}
		}
	}
	switch p.Status {
	case statusNotIntegrated:
		if len(entries) > 0 {
			viol = append(viol, fmt.Sprintf("sqlc.yaml declares %d sql package(s) but status is not-integrated", len(entries)))
		}
		for _, f := range files {
			if !strings.HasSuffix(f, ".go") {
				continue
			}
			hit, err := hasGeneratedHeader(filepath.Join(root, f))
			if err != nil {
				return nil, "", err
			}
			if hit {
				viol = append(viol, fmt.Sprintf("%s carries a sqlc generated header but status is not-integrated", f))
			}
		}
	case statusIntegrated:
		if len(entries) == 0 {
			viol = append(viol, "status is integrated but sqlc.yaml declares no sql packages")
		}
		for i, e := range entries {
			viol = append(viol, validateEntry(i, e)...)
		}
	}
	return viol, p.Status, nil
}

// writeSummary appends to the GitHub step summary when running in Actions;
// stdout already carries the same status, so this is best-effort.
func writeSummary(text string) {
	p := os.Getenv("GITHUB_STEP_SUMMARY")
	if p == "" {
		return
	}
	f, err := os.OpenFile(p, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		return
	}
	defer func() { _ = f.Close() }()
	if _, err := f.WriteString(text); err != nil {
		fmt.Fprintf(os.Stderr, "sqlc-policy: step summary write failed: %v\n", err)
	}
}

// generate is the local/CI generation entry. It always passes through the
// policy gate first — `make gen-sqlc` cannot bypass it — and never
// drift-checks: updating the worktree is the point. Drift verification is
// CI's separate step.
func generate(root string) error {
	viol, status, err := verify(root)
	if err != nil {
		return err
	}
	if len(viol) > 0 {
		return fmt.Errorf("policy gate failed — refusing to generate:\n  %s", strings.Join(viol, "\n  "))
	}
	if status == statusNotIntegrated {
		fmt.Println("sqlc: generation not-applicable (status: not-integrated) — nothing to generate")
		writeSummary("## sqlc\n\n- generation=not-applicable (status: not-integrated; policy gate only — no generation performed or claimed)\n")
		return nil
	}
	fmt.Println("sqlc: running real sqlc generate (status: integrated)")
	cmd := exec.Command("sqlc", "generate")
	cmd.Dir = root
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func main() {
	gen := flag.Bool("generate", false, "run a real sqlc generate, or report generation not-applicable")
	flag.Parse()
	root := "."
	if flag.NArg() > 1 {
		fmt.Fprintln(os.Stderr, "usage: sqlc-policy [--generate] [repo-root]")
		os.Exit(2)
	}
	if flag.NArg() == 1 {
		root = flag.Arg(0)
	}
	if *gen {
		if err := generate(root); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	viol, status, err := verify(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(2)
	}
	for _, v := range viol {
		fmt.Fprintln(os.Stderr, v)
	}
	if len(viol) > 0 {
		os.Exit(1)
	}
	if status == statusNotIntegrated {
		fmt.Println("PASS: sqlc config policy — status=not-integrated; generation not-applicable (no generation claim)")
	} else {
		fmt.Println("PASS: sqlc config policy — status=integrated; generation enforced via --generate")
	}
}
