func TestPolicyFileStrictness(t *testing.T) {
	t.Run("unknown key is a violation", func(t *testing.T) {
		root := repo(t)
		write(t, filepath.Join(root, "sqlc-policy.yaml"), cleanPolicy+"extra: 1\n")
		write(t, filepath.Join(root, "sqlc.yaml"), "version: \"2\"\nsql: []\n")
		got := violations(t, root)
		if len(got) == 0 || !strings.Contains(strings.Join(got, "; "), "unknown key") {
			t.Fatalf("want unknown-key violation, got %v", got)
		}
	})
	t.Run("duplicate key is a violation", func(t *testing.T) {
		root := repo(t)
		write(t, filepath.Join(root, "sqlc-policy.yaml"), cleanPolicy+"status: integrated\n")
		write(t, filepath.Join(root, "sqlc.yaml"), "version: \"2\"\nsql: []\n")
		got := violations(t, root)
		if len(got) == 0 || !strings.Contains(strings.Join(got, "; "), "duplicate key") {
			t.Fatalf("want duplicate-key violation, got %v", got)
		}
	})
	for name, body := range map[string]string{
		"empty reason":      "status: not-integrated\nreason: \"\"\nenable_when: x\n",
		"null reason":       "status: not-integrated\nreason: null\nenable_when: x\n",
		"empty enable_when": "status: not-integrated\nreason: x\nenable_when: \"\"\n",
		"bad status":        "status: maybe\nreason: x\nenable_when: y\n",
		"missing key":       "status: not-integrated\nreason: x\n",
	} {
		t.Run(name, func(t *testing.T) {
			root := repo(t)
			write(t, filepath.Join(root, "sqlc-policy.yaml"), body)
			write(t, filepath.Join(root, "sqlc.yaml"), "version: \"2\"\nsql: []\n")
			if got := violations(t, root); len(got) == 0 {
				t.Fatal("want policy violation")
			}
		})
	}
}

