func TestGenerateIntegratedRequiresBinary(t *testing.T) {
	root := repo(t)
	write(t, filepath.Join(root, "sqlc-policy.yaml"), integratedPolicy)
	write(t, filepath.Join(root, "sqlc.yaml"), integratedSQLC)
	// Keep git reachable — verify runs git ls-files first — so the failure
	// must genuinely come from the missing sqlc executable, not from a
	// PATH that lost every tool.
	gitPath, err := exec.LookPath("git")
	if err != nil {
		t.Skipf("git unavailable: %v", err)
	}
	bin := t.TempDir()
	if err := os.Symlink(gitPath, filepath.Join(bin, "git")); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", bin)
	err = generate(root)
	if err == nil || !strings.Contains(err.Error(), "executable file not found") {
		t.Fatalf("want sqlc executable missing, got %v", err)
	}
}
