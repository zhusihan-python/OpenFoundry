#!/usr/bin/env python3
"""Derive the P2.4 live-guard pin list from the FROZEN P2.3 final archive.

DRAFT (2026-11-14) — part of the P2.4 acceptance-tooling package awaiting
root review. This generator is deterministic, READ-ONLY towards the frozen
archive, and writes only p24_pins.py in THIS directory.

Provenance chain it mechanically enforces (any break ⇒ non-zero exit):
  1. The frozen archive hash-manifest.json covers the source files and
     their SHA256s match (archive integrity precondition).
  2. after-p21abc.json (right after 10b-p21-ABC, suffix 528455c2) and
     after-restart3-full.json (after the final restart3) carry the SAME
     4 controlled rows, identical on all 20 common fields, per
     after-restart3-full-compare.json (rows=4, identical=true, diffs={}).
  3. The two OLD rows equal the ROOT-APPROVED p23_live_guard.py
     PINNED_EXCEPTIONS on every overlapping field (20 common + owner_id +
     requested_by).
  4. The pin list is EXACTLY those 4 rows — never discovered, never
     extended; the generated file embeds the source SHA256s it came from.

Field policy per row (27 keys):
  * the 24 keys of after-restart3-full.json verbatim (safe projection:
    ids/parent chain/identity/time/lease PRESENCE — never holder or
    token values), PLUS
  * conn_org_id / def_org_id / run_org_id — the original generating SQL
    for org_id was not archived, so the guard pins connections.org_id,
    batch_sync_defs.org_id AND sync_runs.org_id all to the same frozen
    org_id value; any divergence blocks (strictness, not forgiveness).

Usage: python3 derive_pins_p24.py   (run from this directory)
"""

import ast
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
P23_TOOLS = HERE.parent / "business-platform-p2-3"
ARCHIVE = P23_TOOLS / "results" / "2026-11-14-p23-final"
ROWS_DIR = ARCHIVE / "new-round-p21-rows"

SOURCES = {  # relpath under ARCHIVE -> role in the chain
    "new-round-p21-rows/after-p21abc.json": "creation snapshot (10b-p21-ABC)",
    "new-round-p21-rows/after-restart3-full.json": "post-restart3 full snapshot",
    "new-round-p21-rows/after-restart3-full-compare.json": "20-field compare verdict",
    "new-round-p21-rows/README.md": "round policy note",
}

# The 4 fixed IDs from the root handoffs (never discovered at runtime).
EXPECTED_IDS = {
    "74d62557-e4e4-4a1a-a5b9-d63f3415d626",   # old B (96351e3b, lease loss)
    "c14b09f0-1341-4127-9e60-23abe7c36739",   # old C (96351e3b, committed-unconfirmed)
    "e08c0b07-4b08-4a88-ba6f-aad4f77eddf2",   # new B (528455c2, lease loss)
    "84055551-5d3b-4ba0-94a9-0bc8738d4335",   # new C (528455c2, committed-unconfirmed)
}

COMMON_20 = ["attempt", "cancel_requested", "control_mode", "finished_at",
             "fixture_src", "gate_entered", "generation", "has_hash",
             "has_holder", "has_token", "has_version", "heartbeat_at", "id",
             "lease_expires_at", "output_dataset_id", "source_id",
             "source_name", "started_at", "status", "sync_def_id"]

EXTRA_ORG_KEYS = ["conn_org_id", "def_org_id", "run_org_id"]


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_p23_pins():
    spec = importlib.util.spec_from_file_location(
        "p23_live_guard", P23_TOOLS / "p23_live_guard.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return {p["id"]: p for p in mod.PINNED_EXCEPTIONS}


def render_pins_module(source_shas, pins):
    T3 = '"""'
    lines = [T3, "GENERATED by derive_pins_p24.py — DO NOT HAND-EDIT.",
             "",
             "P2.4 live-guard pin list: exactly the 4 root-handoff controlled",
             "unknown rows, derived from the FROZEN P2.3 final archive:"]
    for rel, sha in sorted(source_shas.items()):
        lines += [f"  {rel}", f"    sha256 {sha}"]
    lines += [
        "  old B 74d62557…  old C c14b09f0…  (96351e3b, P23-guard-approved)",
        "  new B e08c0b07…  new C 84055551…  (528455c2, P21 ABC this round)",
        "Fields: the 24 frozen safe-projection keys verbatim, plus",
        "conn_org_id/def_org_id/run_org_id — a STRICTER INFERRED-equality",
        "constraint: all three pinned to the archived org_id value. The",
        "archived generating SQL did not record WHICH org column it read;",
        "these three pins are NOT independently-archived historical column",
        "values and await fresh read-only 3-table collection verification",
        "(results/…-p24-final/00-preflight). Never discovers, never forgives.",
        T3, "",
        "PINNED_EXCEPTIONS = " + json.dumps(pins, indent=1, sort_keys=True)]
    return "\n".join(lines) + "\n"


def validate_pins_module_text(text, pins):
    """Root review requirement: --check must not merely compare bytes —
    the generated module must also PARSE and its PINNED_EXCEPTIONS must
    literally equal the derived pins. Raises SyntaxError/ValueError."""
    tree = ast.parse(text)
    found = None
    names = set()
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for tgt in node.targets:
                if isinstance(tgt, ast.Name):
                    names.add(tgt.id)
                    if tgt.id == "PINNED_EXCEPTIONS":
                        found = ast.literal_eval(node.value)
    if found is None or "PINNED_EXCEPTIONS" not in names:
        raise ValueError("PINNED_EXCEPTIONS assignment not found")
    if found != pins:
        raise ValueError("parsed PINNED_EXCEPTIONS != derived pins")
    return True


def main():
    problems = []

    # 1. archive integrity precondition for the files we consume
    manifest = json.loads((ARCHIVE / "hash-manifest.json").read_text())["files"]
    source_shas = {}
    for rel, role in SOURCES.items():
        want = manifest.get(rel)
        got = sha256(ARCHIVE / rel)
        if want is None:
            problems.append(f"{rel}: not covered by frozen hash-manifest.json")
        elif want != got:
            problems.append(f"{rel}: sha256 drift got={got} want={want}")
        else:
            source_shas[rel] = got
            print(f"[derive] {rel}: sha256 ok ({role})")

    creation = json.loads((ROWS_DIR / "after-p21abc.json").read_text())
    full = json.loads((ROWS_DIR / "after-restart3-full.json").read_text())
    cmpj = json.loads((ROWS_DIR / "after-restart3-full-compare.json").read_text())

    # 2. structural + compare verdicts
    if cmpj.get("rows") != 4 or cmpj.get("identical_on_common_set") is not True \
            or cmpj.get("diffs") != {} or cmpj.get("field_count") != 20:
        problems.append(f"compare verdict not (4 rows / identical / no diffs): "
                        f"{cmpj}")
    if sorted(cmpj.get("common_fields", [])) != sorted(COMMON_20):
        problems.append("compare common_fields != expected 20-field set")
    if len(creation) != 4 or len(full) != 4:
        problems.append(f"row counts: creation={len(creation)} full={len(full)}")
    ids_c = {r["id"] for r in creation}
    ids_f = {r["id"] for r in full}
    if ids_c != EXPECTED_IDS or ids_f != EXPECTED_IDS:
        problems.append(f"row id set mismatch vs handoff: "
                        f"creation={sorted(ids_c)} full={sorted(ids_f)}")

    full_by_id = {r["id"]: r for r in full}
    for r in creation:  # 3a. per-row 20-field equality creation vs restart3
        other = full_by_id.get(r["id"])
        if other is None:
            continue
        for f in COMMON_20:
            if r.get(f) != other.get(f):
                problems.append(f"{r['id']}: {f} differs between snapshots: "
                                f"{r.get(f)!r} vs {other.get(f)!r}")

    # 3b. old two rows vs root-approved P23 pins (all overlapping fields)
    p23 = load_p23_pins()
    if set(p23) != {"74d62557-e4e4-4a1a-a5b9-d63f3415d626",
                    "c14b09f0-1341-4127-9e60-23abe7c36739"}:
        problems.append(f"p23_live_guard pins changed: {sorted(p23)}")
    for rid, pin in p23.items():
        row = full_by_id.get(rid)
        if row is None:
            problems.append(f"P23 pin {rid} absent from after-restart3-full")
            continue
        for f, want in pin.items():
            if f in row and row[f] != want:
                problems.append(f"P23 pin {rid} drift on {f}: "
                                f"archive={row[f]!r} pin={want!r}")

    # 4. emit pins: 24 frozen keys verbatim + org triple pinned to org_id
    pins = []
    for rid in sorted(EXPECTED_IDS):
        row = dict(full_by_id[rid])  # copy; values verbatim
        if set(row) != set(COMMON_20) | {"owner_id", "org_id",
                                         "run_owner_id", "requested_by"}:
            problems.append(f"{rid}: unexpected key set {sorted(row)}")
            continue
        org = row["org_id"]
        if not org:
            problems.append(f"{rid}: org_id empty — cannot pin org triple")
        for k in EXTRA_ORG_KEYS:
            row[k] = org
        pins.append(row)

    if problems:
        for p in problems:
            print(f"[derive] BLOCK: {p}", file=sys.stderr)
        return 1

    content = render_pins_module(source_shas, pins)
    try:
        validate_pins_module_text(content, pins)
    except (SyntaxError, ValueError) as exc:
        print(f"[derive] BLOCK: generated module invalid: {exc}",
              file=sys.stderr)
        return 1
    print("[derive] generated module passes ast.parse and value check")
    target = HERE / "p24_pins.py"
    if "--check" in sys.argv[1:]:
        if not target.exists():
            print("[derive] BLOCK: p24_pins.py missing", file=sys.stderr)
            return 1
        if target.read_text() != content:
            print("[derive] BLOCK: p24_pins.py != regenerated content "
                  "(hand-edit or frozen-archive drift)", file=sys.stderr)
            return 1
        print("[derive] ok: p24_pins.py matches regeneration exactly "
              "(syntax + values already validated above)")
        return 0
    target.write_text(content)
    print(f"[derive] ok: {len(pins)} pins x {len(pins[0])} fields -> p24_pins.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
