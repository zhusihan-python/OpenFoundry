#!/bin/bash
# P24-owned compose override renderer (DRAFT 2026-11-14, NOT executed yet).
#
# Renders $TMP/compose-p24-schedule.yaml — the ONLY P24 mechanism that
# turns the scheduler loop on for the acceptance window. It adds
# OPENFOUNDRY_SYNC_SCHEDULER_INTERVAL_SECS (default 1s, contract-bounded
# 1..30; 0/off stays the untouched default everywhere else) to the BASE
# connector and the aux replicas (connector2/connector3, defined by the
# frozen P22 override — merged by compose, never edited). The frozen
# P22 render/stack files are untouched; this file only ever writes the
# P24 override. OPENFOUNDRY_SYNC_SCHEDULER_AUTH_TTL_SECS stays unset
# (code default 300s).
#
# Usage: p24_schedule_env.sh render            # write/refresh the override
#        p24_schedule_env.sh cat               # print it (no secrets — a
#                                              # single non-secret env var)
set -euo pipefail
TMP="${OF_P1_TMP:-/private/tmp/openfoundry-platform-p1-q3v9}"
OUT="$TMP/compose-p24-schedule.yaml"
INTERVAL="${OF_P24_INTERVAL:-1}"

if [ "${1:-}" = "cat" ]; then
  cat "$OUT"
  exit $?
fi
[ "${1:-}" = "render" ] || { echo "usage: $0 render|cat" >&2; exit 2; }
if ! [[ "$INTERVAL" =~ ^[0-9]+$ ]] || [ "$INTERVAL" -lt 1 ] || [ "$INTERVAL" -gt 30 ]; then
  echo "p24-schedule-env: OF_P24_INTERVAL=$INTERVAL outside contract bound 1..30" >&2
  exit 1
fi

# collision-safe history: a previous override is kept, never overwritten
n=0
while [ -e "$OUT" ]; do
  n=$((n + 1)); OUT="$TMP/compose-p24-schedule-r$n.yaml"
done
mkdir -p "$(dirname "$OUT")"

cat > "$OUT" <<YAML
# GENERATED by p24_schedule_env.sh (P24 tools) — scheduler-loop enable
# for the acceptance window only. Non-secret single env var per service.
services:
  connector:
    environment:
      OPENFOUNDRY_SYNC_SCHEDULER_INTERVAL_SECS: "${INTERVAL}"
  connector2:
    environment:
      OPENFOUNDRY_SYNC_SCHEDULER_INTERVAL_SECS: "${INTERVAL}"
  connector3:
    environment:
      OPENFOUNDRY_SYNC_SCHEDULER_INTERVAL_SECS: "${INTERVAL}"
YAML
echo "p24-schedule-env: wrote $OUT (interval=${INTERVAL}s)"
# MACHINE INTERFACE (the formal runner captures these, never prose)
echo "OVERRIDE_FILE=$OUT"
echo "OVERRIDE_INTERVAL=$INTERVAL"
# the formal runner composes with:
#   -f compose.yaml -f compose-p22-connector2.yaml -f <this override>
